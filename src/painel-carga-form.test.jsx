// @vitest-environment jsdom
import React from 'react';
import {afterEach,it,expect,vi} from 'vitest';
import {render,screen,fireEvent,waitFor,cleanup} from '@testing-library/react';
import {PainelCargaForm} from './screens/painel-carga-form.jsx';
afterEach(()=>{cleanup();delete window.RB_API;});
const items=[{placa:'AAA1B23',carga:{codigo:'carregado',label:'Carregado'},contextoCarga:'b'.repeat(64)},{placa:'RXO6C18',carga:{codigo:'conferir',label:'Conferir carga'},contextoCarga:'a'.repeat(64)}];
it('prioritizes uncertain vehicles, saves the operation context and refreshes the panel',async()=>{
 window.RB_API={getPainelCargaHistorico:vi.fn().mockResolvedValue({registros:[]}),savePainelCarga:vi.fn().mockResolvedValue({})};
 const onClose=vi.fn(),onSaved=vi.fn().mockResolvedValue();
 render(<PainelCargaForm items={items} onClose={onClose} onSaved={onSaved}/>);
 expect(screen.getByLabelText('Veículo').value).toBe('RXO6C18');
 fireEvent.click(screen.getByRole('button',{name:/^Vazio/}));
 fireEvent.change(screen.getByLabelText('Motivo / observação'),{target:{value:'Descarga confirmada pelo motorista'}});
 fireEvent.submit(screen.getByRole('button',{name:'Salvar confirmação'}).closest('form'));
 await waitFor(()=>expect(screen.getByRole('heading',{name:/conclu/})).toBeTruthy());
 expect(onClose).not.toHaveBeenCalled();
 expect(window.RB_API.savePainelCarga).toHaveBeenCalledWith(expect.objectContaining({placa:'RXO6C18',situacao:'vazio',contexto:'a'.repeat(64)}));
 expect(onSaved).toHaveBeenCalled();
});
it('keeps the form open with the error when the operation changed',async()=>{
 window.RB_API={getPainelCargaHistorico:vi.fn().mockResolvedValue({registros:[]}),savePainelCarga:vi.fn().mockRejectedValue(new Error('A operação mudou.'))};
 const onClose=vi.fn();render(<PainelCargaForm items={items} onClose={onClose} onSaved={vi.fn()}/>);
 fireEvent.click(screen.getByRole('button',{name:/^Carregado/}));
 fireEvent.change(screen.getByRole('textbox'),{target:{value:'Carga confirmada pelo motorista'}});
 fireEvent.submit(screen.getByRole('button',{name:'Salvar confirmação'}).closest('form'));
 expect(await screen.findByRole('alert')).toBeTruthy();expect(onClose).not.toHaveBeenCalled();
});
it('uses quick reasons, resets them on status change and advances only after a saved confirmation',async()=>{
 window.RB_API={getPainelCargaHistorico:vi.fn().mockResolvedValue({registros:[]}),savePainelCarga:vi.fn().mockResolvedValue({})};
 const list=items.map(item=>({...item,carga:{...item.carga,confirmacaoPendente:true}}));
 render(<PainelCargaForm items={list} onClose={vi.fn()} onSaved={vi.fn()}/>);
 const initial=screen.getByLabelText('Veículo').value;
 expect(screen.getByRole('button',{name:'Salvar confirmação'}).disabled).toBe(true);
 fireEvent.click(screen.getByRole('button',{name:/^Vazio/}));
 expect(screen.queryByLabelText('Manter situação até')).toBeNull();
 fireEvent.click(screen.getByRole('button',{name:/Última entrega concluída/}));
 expect(screen.getByText('3/3 etapas')).toBeTruthy();
 fireEvent.click(screen.getByRole('button',{name:/^Carregado/}));
 expect(screen.getByRole('textbox').value).toBe('');
 expect(screen.getByLabelText('Manter situação até')).toBeTruthy();
 fireEvent.click(screen.getByRole('button',{name:/Carregamento concluído no cliente/}));
 fireEvent.click(screen.getByRole('button',{name:'Salvar confirmação'}));
 await screen.findByRole('heading',{name:'Conferência concluída!'});
 fireEvent.click(screen.getByRole('button',{name:/Conferir próximo/}));
 expect(screen.getByLabelText('Veículo').value).not.toBe(initial);
 expect(screen.getByRole('textbox').value).toBe('');
 expect(screen.getByText('1/3 etapas')).toBeTruthy();
});
it('prevents duplicate submissions and retains success if refreshing the panel fails',async()=>{
 let finish;
 window.RB_API={getPainelCargaHistorico:vi.fn().mockResolvedValue({registros:[]}),savePainelCarga:vi.fn().mockImplementation(()=>new Promise(resolve=>{finish=resolve;}))};
 render(<PainelCargaForm items={items} onClose={vi.fn()} onSaved={vi.fn().mockRejectedValue(new Error('offline'))}/>);
 fireEvent.click(screen.getByRole('button',{name:/^Vazio/}));
 fireEvent.click(screen.getByRole('button',{name:/Última entrega concluída/}));
 const form=screen.getByRole('button',{name:'Salvar confirmação'}).closest('form');
 fireEvent.submit(form);fireEvent.submit(form);
 expect(window.RB_API.savePainelCarga).toHaveBeenCalledTimes(1);
 finish({});
 expect(await screen.findByRole('heading',{name:'Conferência concluída!'})).toBeTruthy();
 expect(await screen.findByRole('alert')).toHaveProperty('textContent',expect.stringContaining('Confirmação salva'));
 expect(screen.queryByRole('button',{name:'Salvar confirmação'})).toBeNull();
});
